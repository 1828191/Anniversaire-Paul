create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  first_name text not null check (char_length(trim(first_name)) between 1 and 80),
  last_name text not null check (char_length(trim(last_name)) between 1 and 80),
  attendance boolean not null,
  guest_count integer not null default 0 check (
    (attendance = true and guest_count >= 1)
    or
    (attendance = false and guest_count = 0)
  ),
  message text check (message is null or char_length(message) <= 1000),
  responded_at timestamptz not null default now()
);

alter table public.registrations enable row level security;

drop policy if exists "Public can submit registrations" on public.registrations;
create policy "Public can submit registrations"
on public.registrations
for insert
to anon, authenticated
with check (true);

drop policy if exists "Public dashboard can read registrations" on public.registrations;
create policy "Public dashboard can read registrations"
on public.registrations
for select
to anon, authenticated
using (true);

grant usage on schema public to anon, authenticated;
grant select, insert on public.registrations to anon, authenticated;
grant usage, select on sequence public.registrations_id_seq to anon, authenticated;

-- L'ancien système n'est plus utilisé par le nouveau site.
-- Ces révocations empêchent les visiteurs anonymes d'utiliser directement
-- les anciennes tables tout en conservant les anciennes données dans Supabase.
revoke all on table public.guests from anon, authenticated;
revoke all on table public.responses from anon, authenticated;
