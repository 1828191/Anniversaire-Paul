create table if not exists public.registration_groups (
 id bigint generated by default as identity primary key,
 attendance boolean not null,
 message text check (message is null or char_length(message)<=1000),
 responded_at timestamptz not null default now()
);
create table if not exists public.registration_people (
 id bigint generated by default as identity primary key,
 registration_id bigint not null references public.registration_groups(id) on delete cascade,
 first_name text not null check (char_length(trim(first_name)) between 1 and 80),
 last_name text not null check (char_length(trim(last_name)) between 1 and 80),
 normalized_name text not null
);
alter table public.registration_groups enable row level security;
alter table public.registration_people enable row level security;
revoke all on public.registration_groups from anon,authenticated;
revoke all on public.registration_people from anon,authenticated;

create or replace function public.normalize_person_name_v74(p_first text,p_last text) returns text
language sql immutable set search_path=public as $$
 select trim(regexp_replace(lower(translate(trim(p_first)||' '||trim(p_last),'àáâäãåçèéêëìíîïñòóôöõùúûüýÿœæ','aaaaaaceeeeiiiinooooouuuuyyoa')),'[^a-z0-9]+',' ','g'));
$$;

create or replace function public.submit_registration_v74(p_attendance boolean,p_message text,p_people jsonb) returns bigint
language plpgsql security definer set search_path=public as $$
declare rid bigint; x jsonb; fn text; ln text; nn text;
begin
 if p_people is null or jsonb_typeof(p_people)<>'array' or jsonb_array_length(p_people)<1 or jsonb_array_length(p_people)>20 then raise exception 'INVALID_PEOPLE_COUNT'; end if;
 if not p_attendance and jsonb_array_length(p_people)<>1 then raise exception 'ABSENT_REQUIRES_ONE_PERSON'; end if;
 insert into public.registration_groups(attendance,message) values(p_attendance,nullif(trim(p_message),'')) returning id into rid;
 for x in select value from jsonb_array_elements(p_people) loop
  fn:=trim(coalesce(x->>'first_name','')); ln:=trim(coalesce(x->>'last_name',''));
  if char_length(fn) not between 1 and 80 or char_length(ln) not between 1 and 80 then raise exception 'INVALID_PERSON_NAME'; end if;
  nn:=public.normalize_person_name_v74(fn,ln);
  if exists(select 1 from public.registration_people where normalized_name=nn) then raise exception 'DUPLICATE_PERSON'; end if;
  insert into public.registration_people(registration_id,first_name,last_name,normalized_name) values(rid,fn,ln,nn);
 end loop;
 return rid;
end;$$;

create or replace view public.registration_people_dashboard_v74 as
select p.id person_id,g.id registration_id,p.first_name,p.last_name,g.attendance,g.message,g.responded_at
from public.registration_people p join public.registration_groups g on g.id=p.registration_id;

create or replace function public.delete_registration_person_v74(p_person_id bigint) returns void
language plpgsql security definer set search_path=public as $$
declare rid bigint; begin
 select registration_id into rid from public.registration_people where id=p_person_id;
 delete from public.registration_people where id=p_person_id;
 if rid is not null and not exists(select 1 from public.registration_people where registration_id=rid) then delete from public.registration_groups where id=rid; end if;
end;$$;

revoke all on function public.submit_registration_v74(boolean,text,jsonb) from public;
revoke all on function public.delete_registration_person_v74(bigint) from public;
grant execute on function public.submit_registration_v74(boolean,text,jsonb) to anon,authenticated;
grant execute on function public.delete_registration_person_v74(bigint) to anon,authenticated;
grant select on public.registration_people_dashboard_v74 to anon,authenticated;
